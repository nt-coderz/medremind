function buildLocale(template, fallback) {
  return {
    common: {
      ...fallback.common,
      appName: template.appName || fallback.common.appName,
      signIn: template.signIn || fallback.common.signIn,
      createAccount: template.createAccount || fallback.common.createAccount
    },
    nav: {
      ...fallback.nav,
      dashboard: template.home || fallback.nav.dashboard,
      medicines: template.meds || fallback.nav.medicines,
      scanner: template.scan || fallback.nav.scanner,
      schedule: template.schedule || fallback.nav.schedule,
      history: template.history || fallback.nav.history,
      profile: template.profile || fallback.nav.profile,
      overview: template.overview || fallback.nav.overview,
      users: template.users || fallback.nav.users,
      auditLog: template.audit || fallback.nav.auditLog,
      settings: template.settings || fallback.nav.settings
    },
    welcome: {
      ...fallback.welcome,
      careWithClarity: template.care || fallback.welcome.careWithClarity,
      headline: template.headline || fallback.welcome.headline
    },
    auth: {
      ...fallback.auth,
      signInTitle: template.signIn ? `${fallback.common.appName} - ${template.signIn}` : fallback.auth.signInTitle,
      createAccountTitle: template.createAccount || fallback.auth.createAccountTitle,
      fullName: template.fullName || fallback.auth.fullName,
      dob: template.dob || fallback.auth.dob,
      gender: template.gender || fallback.auth.gender,
      email: template.email || fallback.auth.email,
      phone: template.phone || fallback.auth.phone,
      password: template.pass || fallback.auth.password,
      signInButton: template.signIn || fallback.auth.signInButton,
      createAccountButton: template.createAccount || fallback.auth.createAccountButton
    },
    admin: {
      ...fallback.admin,
      title: `${fallback.common.appName} Admin Console`,
      systemOverview: template.overview ? `${template.overview} (System Overview)` : fallback.admin.systemOverview,
      totalUsers: template.totalUsers || fallback.admin.totalUsers,
      patients: template.patients || fallback.admin.patients,
      activeAccounts: template.activeAcc || fallback.admin.activeAccounts,
      medications: template.medCount || fallback.admin.medications
    },
    dashboard: fallback.dashboard,
    medicines: fallback.medicines,
    scanner: fallback.scanner,
    profile: fallback.profile,
    history: fallback.history
  };
}

// 22 scheduled Indian languages list
const allCodes = [
  'en', 'hi', 'bn', 'doi', 'as', 'brx', 'gu', 'kn', 'ks', 'kok', 
  'mai', 'ml', 'mni', 'mr', 'ne', 'or', 'pa', 'sa', 'sat', 'sd', 
  'ta', 'te', 'ur'
];

// Write master languages
fs.writeFileSync(path.join(localesDir, 'en.json'), JSON.stringify(en, null, 2));
fs.writeFileSync(path.join(localesDir, 'hi.json'), JSON.stringify(hi, null, 2));
fs.writeFileSync(path.join(localesDir, 'doi.json'), JSON.stringify(doi, null, 2));
fs.writeFileSync(path.join(localesDir, 'bn.json'), JSON.stringify(bn, null, 2));

// Generate others
for (const code of allCodes) {
  if (['en', 'hi', 'doi', 'bn'].includes(code)) continue;
  const tmpl = regionalTemplates[code];
  const localeData = tmpl ? buildLocale(tmpl, hi) : buildLocale({}, hi);
  fs.writeFileSync(path.join(localesDir, `${code}.json`), JSON.stringify(localeData, null, 2));
}

